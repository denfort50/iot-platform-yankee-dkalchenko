package ru.dkalchenko.device.audit;

/**
 * Сервис записи аудита операций над устройствами.
 * Реализация не должна блокировать основной поток и не должна приводить
 * к падению бизнес-операции при сбое записи аудита.
 */
public interface DeviceAuditService {

	/**
	 * Записать событие аудита (успех, неуспех, not found).
	 * Вызов выполняется асинхронно, ошибки логируются и не пробрасываются.
	 *
	 * @param event событие аудита
	 */
	void record(DeviceAuditEvent event);
}
